// Makes single-file copies of each Edge Function, so they can be pasted into the
// Supabase dashboard's function editor (no CLI needed).
//   node scripts/bundle-for-dashboard.mjs
// Output: dashboard/<function>.ts

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fnDir = join(root, 'supabase', 'functions');
const outDir = join(root, 'dashboard');
mkdirSync(outDir, { recursive: true });

// Shared modules in dependency order.
const ORDER = ['types', 'util', 'categories', 'fsa', 'opss', 'mhra', 'vmd', 'fss', 'matching', 'push', 'images'];

function strip(source) {
  return source
    // drop local imports (single or multi-line), keep npm: imports
    .replace(/^import\s+(type\s+)?[\s\S]*?from\s+'\.{1,2}\/[^']+';\s*$/gm, '')
    // drop the "export" keyword; everything lives in one file now
    .replace(/^export\s+(?=(async\s+)?(function|const|let|class|type|interface)\b)/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const NEEDS = {
  'collect-recalls': ORDER,
  'daily-digest': ['util', 'push'],
};

for (const [fn, modules] of Object.entries(NEEDS)) {
  const entry = readFileSync(join(fnDir, fn, 'index.ts'), 'utf8');
  const npmImports = [...entry.matchAll(/^import .* from 'npm:[^']+';$/gm)].map((m) => m[0]);
  const entryBody = strip(entry.replace(/^import .* from 'npm:[^']+';$/gm, ''));
  const parts = [
    `// Heads Up Home — ${fn} (single-file version for the Supabase dashboard editor).`,
    `// Generated by scripts/bundle-for-dashboard.mjs from supabase/functions. Edit those files, not this one.`,
    '',
    ...npmImports,
    '',
    ...modules.map((m) => `// ───────── ${m}.ts ─────────\n${strip(readFileSync(join(fnDir, '_shared', `${m}.ts`), 'utf8'))}`),
    `// ───────── ${fn}/index.ts ─────────\n${entryBody}`,
    '',
  ];
  const out = parts.join('\n\n').replace(/\n{3,}/g, '\n\n');
  writeFileSync(join(outDir, `${fn}.ts`), out);
  console.log(`dashboard/${fn}.ts  ${out.length} chars`);
}
